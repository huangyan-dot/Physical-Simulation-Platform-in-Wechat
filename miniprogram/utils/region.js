// 使 g 的跨度达到 9.780~9.812 m/s²。需要更多县时直接往对应省份数组里加即可。
//
// 例外：北京、天津、上海、重庆四个直辖市收录全部区县。直辖市下面没有地级市，
// 学生要直接选到区，列表里缺哪个区，住那儿的学生就只能选错的。
// 这是可用性问题而不是精度问题：重庆虽然跨纬度 3.4°，但区县之间 g 的最大差异
// 只有 0.031%（开州 9.79355 vs 秀山 9.79051），原来 7 条的表就近匹配
// 最坏也只偏 0.014%（南川 → 涪陵，相距 66km），远在满分容差内。

/**
 * 由纬度和海拔计算当地重力加速度。必须与后端 service.LocalGravity 保持一致。
 * @param {number} latDeg 纬度（度，北正南负）
 * @param {number} altM 海拔（米）
 * @returns {number} g，单位 m/s²
 */
export function localGravity(latDeg, altM) {
  const phi = (latDeg * Math.PI) / 180;
  const s2 = Math.pow(Math.sin(phi), 2);
  const s4 = s2 * s2;
  const s6 = s4 * s2;
  const g =
    9.7803267715 *
    (1 + 0.0052790414 * s2 + 0.0000232718 * s4 + 0.0000001262 * s6);
  return g - 3.086e-6 * (altM || 0);
}

