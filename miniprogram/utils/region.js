//
// 单摆实验测的是「当地」重力加速度，g 随纬度和海拔变化：
//   纬度越高 g 越大（地球自转离心效应 + 极半径更小）
//   海拔越高 g 越小（离地心更远）
//
// 采用 WGS84 正常重力公式（国际重力公式 1980 的椭球形式）+ 自由空气改正：
//   g(φ,h) = 9.7803267715·(1 + 0.0052790414·sin²φ + 0.0000232718·sin⁴φ + 0.0000001262·sin⁶φ)
//            − 3.086×10⁻⁶·h
// 校验：φ=0 → 9.78033；φ=45° → 9.80620；φ=90° → 9.83219（与公认值一致）
//
// 注意：下面的县级地区表是「精选子集」，不是全国 2800+ 个县的全量表。
// 它覆盖全部 34 个省级行政区，并特意包含纬度与海拔的极端点
