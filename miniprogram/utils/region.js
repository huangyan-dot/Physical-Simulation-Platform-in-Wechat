/** 省级名称列表（picker 第一列） */
export function provinceNames() {
  return REGIONS.map((p) => p[0]);
}

/** 某省下的县级名称列表（picker 第二列） */
export function countyNames(provinceIndex) {
  const p = REGIONS[provinceIndex];
  return p ? p[1].map((c) => c[0]) : [];
}

/** 组装一个地区对象，附带算好的 g */
function makeRegion(provinceIndex, countyIndex, source) {
  const p = REGIONS[provinceIndex];
  if (!p) return null;
  const c = p[1][countyIndex];
  if (!c) return null;
  const [name, lat, lon, alt] = c;
  return {
    province: p[0],
    county: name,
    // 省名已含在县名里时（如「北京市 东城区」）不重复拼接省名
    label: p[0] === name ? name : `${p[0]} ${name}`,
    latitude: lat,
    longitude: lon,
    altitude: alt,
    gravity: Number(localGravity(lat, alt).toFixed(4)),
    provinceIndex,
    countyIndex,
    source: source || 'manual'
  };
}

/** 按 picker 下标取地区 */
export function regionByIndex(provinceIndex, countyIndex, source) {
  return makeRegion(provinceIndex, countyIndex, source);
}

/**
 * 由经纬度就近匹配县级地区。
 * 用等距圆柱近似算球面距离：经度差按 cos(纬度) 收缩，足够选出最近的表内条目。
 */
export function nearestRegion(latitude, longitude) {
  let best = null;
  let bestD = Infinity;
  const latRad = (latitude * Math.PI) / 180;
  const cosLat = Math.cos(latRad);
  for (let pi = 0; pi < REGIONS.length; pi++) {
    const counties = REGIONS[pi][1];
    for (let ci = 0; ci < counties.length; ci++) {
      const dLat = counties[ci][1] - latitude;
      const dLon = (counties[ci][2] - longitude) * cosLat;
      const d = dLat * dLat + dLon * dLon;
      if (d < bestD) {
        bestD = d;
        best = [pi, ci];
      }
    }
  }
  if (!best) return null;
  const r = makeRegion(best[0], best[1], 'gps');
  // 111 km/度：把角度距离换成公里，供 UI 提示匹配精度
  r.distanceKm = Math.round(Math.sqrt(bestD) * 111);
  return r;
}

/** 默认地区（定位失败且未手选时的兜底）：北京市东城区 */
export function defaultRegion() {
  return makeRegion(0, 0, 'default');
}
